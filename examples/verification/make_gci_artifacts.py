"""Generate the GCI study artifacts (JSON + figures) for mission m1646.

Usage::

    python3 examples/verification/make_gci_artifacts.py [outdir]

Writes ``<outdir>/gci_mms_study.json`` and two PNGs:

* ``fig_gci_order.png``  -- log-log error vs cell size with the observed slope
  for each scheme (code-verification view);
* ``fig_gci_band.png``   -- fine-grid value with its GCI band, the Richardson
  extrapolation and the exact reference (uncertainty-validation view).

Every number in the JSON/figures comes from this run; nothing is hand-copied.
"""

from __future__ import annotations

import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.dirname(os.path.dirname(_HERE))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from examples.verification.gci_mms_study import run_study  # noqa: E402

LABELS = {
    "advdiff-central": "1D adv-diff, 2nd-order central (formal p=2)",
    "advdiff-upwind": "1D adv-diff, 1st-order upwind (formal p=1)",
    "poisson2d-fv5": "2D Poisson, 5-point (formal p=2)",
}
COLORS = {"advdiff-central": "#1f77b4", "advdiff-upwind": "#d62728",
          "poisson2d-fv5": "#2ca02c"}


def fig_order(study: dict, path: str) -> None:
    fig, ax = plt.subplots(figsize=(7.0, 5.0))
    for name, case in study["cases"].items():
        h = np.array(case["h_coarse_to_fine"], dtype=float)
        err = np.array(case["raw_errors_coarse_to_fine"], dtype=float)
        ax.loglog(h, err, "o-", color=COLORS[name], label=LABELS[name], lw=1.5, ms=6)
        p = case["gci"]["p"]
        # Reference slope drawn through the finest point for visual comparison.
        if p is not None:
            ref = err[0] * (h / h[0]) ** p
            ax.loglog(h, ref, ":", color=COLORS[name], lw=1.0, alpha=0.8)
            ax.annotate(f"p_obs = {p:.3f}", xy=(h[-1], ref[-1]),
                        xytext=(6, -2), textcoords="offset points",
                        color=COLORS[name], fontsize=9)
    ax.set_xlabel("representative cell size  h")
    ax.set_ylabel(r"$|\phi_h - \phi_{\mathrm{exact}}|$")
    ax.set_title("Code verification: observed vs formal order of accuracy\n"
                 "(dotted = fitted p through the finest grid)")
    ax.grid(True, which="both", ls=":", alpha=0.5)
    ax.legend(fontsize=8, loc="lower right")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def fig_band(study: dict, path: str) -> None:
    names = list(study["cases"])
    fig, ax = plt.subplots(figsize=(7.4, 4.8))
    for i, name in enumerate(names):
        case = study["cases"][name]
        g = case["gci"]
        phi1 = g["phi"][0]
        half = case["band_half_width_abs"]
        ax.errorbar(i - 0.12, phi1, yerr=half, fmt="o", ms=7, capsize=8,
                    color=COLORS[name], label=f"{name}: phi_h (fine grid) +- GCI")
        ax.plot(i + 0.12, g["phi_ext"], "D", ms=7, color=COLORS[name],
                markeredgecolor="k", label=f"{name}: Richardson phi_ext")
        ax.hlines(case["exact"], i - 0.35, i + 0.35, colors="k", linestyles="--",
                  lw=1.0)
        ax.annotate(f"{case['extrapolated_rel_error']:.1e}",
                    xy=(i + 0.12, g["phi_ext"]), xytext=(10, 8),
                    textcoords="offset points", fontsize=8)
    ax.set_xticks(range(len(names)))
    ax.set_xticklabels([f"{n}\n(exact = 1.0)" for n in names], fontsize=8)
    ax.set_ylabel(r"quantity of interest  $\phi$")
    ax.set_title("Uncertainty validation: GCI band must bracket the exact value\n"
                 "(dashed = exact; annotations = relative error of $\phi_{ext}$)")
    ax.grid(True, axis="y", ls=":", alpha=0.5)
    ax.legend(fontsize=7, loc="best")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)


def write_tables(study: dict, path: str) -> None:
    """Auto-generated result tables -- the report quotes these verbatim."""
    lines = [
        "<!-- AUTO-GENERATED by examples/verification/make_gci_artifacts.py",
        "     from artifacts/verification/gci_mms_study.json; do not edit by hand. -->",
        "",
        "### Table 1 -- code verification (observed vs formal order)",
        "",
        "| case | scheme | grids (coarse -> fine) | p formal | p observed | "
        "|p_obs - p_formal|/p_formal | regime | R |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, c in study["cases"].items():
        g = c["gci"]
        p_err = abs(g["p"] - c["formal_p"]) / c["formal_p"]
        lines.append(
            f"| `{name}` | {c['scheme']} | {c['grid_sizes_coarse_to_fine']} | "
            f"{c['formal_p']:.0f} | {g['p']:.4f} | {p_err*100:.2f} % | {g['regime']} | "
            f"{g['R']:.4f} |"
        )
    lines += [
        "",
        "### Table 2 -- uncertainty validation (GCI band vs exact value)",
        "",
        "| case | exact | fine-grid phi_h | Richardson phi_ext | "
        "|phi_ext-exact|/exact | |phi_h-exact| | GCI_half_width | band brackets exact | "
        "extrapolation beats fine grid |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, c in study["cases"].items():
        g = c["gci"]
        lines.append(
            f"| `{name}` | {c['exact']:.1f} | {g['phi'][0]:.10f} | "
            f"{g['phi_ext']:.10f} | {c['extrapolated_rel_error']:.3e} | "
            f"{c['fine_grid_error_abs']:.3e} | {c['band_half_width_abs']:.3e} | "
            f"{c['band_contains_truth']} | {c['extrapolation_beats_fine_grid']} |"
        )
    lines += [
        "",
        "### Table 3 -- pre-asymptotic ladder (1st-order upwind, same QoI)",
        "",
        "| grids (coarse -> fine) | p observed | Richardson phi_ext | "
        "|phi_ext-exact|/exact | GCI [%] |",
        "|---|---|---|---|---|",
    ]
    for row in study["upwind_order_ladder"]:
        lines.append(
            f"| {row['grid_sizes_coarse_to_fine']} | {row['p_observed']:.4f} | "
            f"{row['phi_ext']:.10f} | {row['extrapolated_rel_error']:.3e} | "
            f"{row['gci_fine_pct']:.3f} |"
        )
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", path)


def main() -> int:
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        _REPO_ROOT, "artifacts", "verification")
    os.makedirs(outdir, exist_ok=True)
    study = run_study()
    study["mission"] = 1646
    study["toolkit"] = "src/verification/gci.py"
    study["references"] = [
        "Roache 1994, J. Fluids Eng. 116:405-413",
        "Celik, Ghia, Roache et al. 2008, J. Fluids Eng. 130:078001",
        "ASME V&V 20-2009",
    ]
    jpath = os.path.join(outdir, "gci_mms_study.json")
    with open(jpath, "w") as fh:
        json.dump(study, fh, indent=2)
    write_tables(study, os.path.join(_REPO_ROOT, "docs", "verification",
                                     "gci_results_tables.md"))
    fig_order(study, os.path.join(outdir, "fig_gci_order.png"))
    fig_band(study, os.path.join(outdir, "fig_gci_band.png"))
    print("wrote", jpath)
    for name, case in study["cases"].items():
        g = case["gci"]
        print(f"{name:16s} p_formal={case['formal_p']:.0f} p_obs={g['p']:.4f} "
              f"phi_ext={g['phi_ext']:.10f} |err|={case['extrapolated_rel_error']:.3e} "
              f"GCI={g['gci_fine_pct']:.3e}% band_ok={case['band_contains_truth']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())