"""API for monitoring newly arriving industrial time-series data."""
from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field, field_validator

from api.deps import require_auth, require_permission
from services.datasource_service import validate_read_only_query
from services.realtime_sensor_monitor_service import get_realtime_sensor_monitor_service

router = APIRouter(prefix="/realtime-sensor-monitors", tags=["实时仪表监测"])


class MonitorRequest(BaseModel):
    name: str = Field(min_length=1, max_length=160)
    source_id: str = Field(min_length=1, max_length=128)
    query_sql: str = Field(min_length=8, max_length=20000)
    time_column: str = Field(min_length=1, max_length=128)
    fields: list[str] = Field(min_length=1, max_length=50)
    poll_interval_seconds: int = Field(default=60, ge=15, le=86400)
    freeze_points: int = Field(default=20, ge=3, le=10000)
    jump_sigma: float = Field(default=6.0, ge=1.0, le=20.0)
    stale_seconds: int = Field(default=300, ge=30, le=604800)

    @field_validator("query_sql")
    @classmethod
    def validate_query(cls, value: str) -> str:
        # Replace the platform placeholder only for validation; its actual value
        # is generated by the service, never supplied by a browser.
        return validate_read_only_query(value.replace("{last_timestamp}", "1970-01-01 00:00:00"))

    @field_validator("fields")
    @classmethod
    def validate_fields(cls, values: list[str]) -> list[str]:
        result = list(dict.fromkeys(str(item).strip() for item in values if str(item).strip()))
        if not result:
            raise ValueError("至少选择一个需监测的数值测点")
        return result


class MonitorUpdate(BaseModel):
    name: Optional[str] = Field(default=None, min_length=1, max_length=160)
    query_sql: Optional[str] = Field(default=None, min_length=8, max_length=20000)
    time_column: Optional[str] = Field(default=None, min_length=1, max_length=128)
    fields: Optional[list[str]] = None
    poll_interval_seconds: Optional[int] = Field(default=None, ge=15, le=86400)
    freeze_points: Optional[int] = Field(default=None, ge=3, le=10000)
    jump_sigma: Optional[float] = Field(default=None, ge=1.0, le=20.0)
    stale_seconds: Optional[int] = Field(default=None, ge=30, le=604800)
    enabled: Optional[bool] = None


def _owner(user: dict) -> dict:
    if not user.get("organization_id"):
        raise HTTPException(status_code=400, detail="当前用户未归属组织，不能创建实时监测")
    return {"id": int(user["id"]), "organization_id": int(user["organization_id"])}


@router.get("", dependencies=[Depends(require_permission("datasets:read"))])
def list_monitors(current_user: dict = Depends(require_auth)):
    return {"items": get_realtime_sensor_monitor_service().list_monitors(_owner(current_user)["organization_id"])}


@router.post("", dependencies=[Depends(require_permission("datasets:connect"))])
def create_monitor(request: MonitorRequest, current_user: dict = Depends(require_auth)):
    payload = request.model_dump()
    return get_realtime_sensor_monitor_service().create_monitor(_owner(current_user), payload)


@router.post("/{monitor_id}/run", dependencies=[Depends(require_permission("datasets:connect"))])
def run_monitor(monitor_id: str, current_user: dict = Depends(require_auth)):
    try:
        return get_realtime_sensor_monitor_service().run_monitor(monitor_id, _owner(current_user)["organization_id"])
    except KeyError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc


@router.put("/{monitor_id}", dependencies=[Depends(require_permission("datasets:connect"))])
def update_monitor(monitor_id: str, request: MonitorUpdate, current_user: dict = Depends(require_auth)):
    values = request.model_dump(exclude_unset=True)
    if "query_sql" in values:
        values["query_sql"] = validate_read_only_query(values["query_sql"].replace("{last_timestamp}", "1970-01-01 00:00:00"))
    if "fields" in values:
        values["fields"] = list(dict.fromkeys(str(item).strip() for item in values["fields"] if str(item).strip()))
        if not values["fields"]:
            raise HTTPException(status_code=400, detail="至少选择一个需监测的数值测点")
    if not get_realtime_sensor_monitor_service().update_monitor(monitor_id, _owner(current_user)["organization_id"], values):
        raise HTTPException(status_code=404, detail="监测任务不存在")
    return {"message": "实时监测已更新"}


@router.delete("/{monitor_id}", dependencies=[Depends(require_permission("datasets:connect"))])
def delete_monitor(monitor_id: str, current_user: dict = Depends(require_auth)):
    if not get_realtime_sensor_monitor_service().delete_monitor(monitor_id, _owner(current_user)["organization_id"]):
        raise HTTPException(status_code=404, detail="监测任务不存在")
    return {"message": "实时监测已删除"}


@router.get("/alerts/list", dependencies=[Depends(require_permission("datasets:read"))])
def list_alerts(monitor_id: Optional[str] = None, current_user: dict = Depends(require_auth)):
    return {"items": get_realtime_sensor_monitor_service().list_alerts(_owner(current_user)["organization_id"], monitor_id)}
