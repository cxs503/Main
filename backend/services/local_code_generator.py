def _normalise(value: str | None, allowed: set[str], default: str) -> str:
    candidate = re.sub(r"[^a-z0-9_]+", "_", str(value or "").strip().lower()).strip("_")
    return candidate if candidate in allowed else default


def _header(requirement: str, task: str, framework: str) -> str:
    safe_requirement = " ".join(str(requirement or "").split())[:500]
    return (
        "# Generated by Open Foundation local template mode.\n"
        f"# Task: {task}\n# Framework: {framework}\n# Requirement: {safe_requirement}\n"
    )


