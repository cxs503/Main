def generate_local_code(
    requirement: str,
    language: str = "python",
    task: str | None = None,
    framework: str | None = None,
    algorithm: str | None = None,
) -> str:
    if str(language).lower() != "python":
        raise ValueError("本地模板模式目前仅支持 Python")
    safe_task = _normalise(task, SUPPORTED_TASKS, "regression")
    safe_framework = _normalise(framework, SUPPORTED_FRAMEWORKS, "sklearn")
    default_algorithm = {
        "pytorch": "mlp",
        "tensorflow": "mlp",
        "xgboost": "xgboost",
        "lightgbm": "lightgbm",
    }.get(safe_framework, "random_forest")
    safe_algorithm = _normalise(algorithm, SUPPORTED_ALGORITHMS, default_algorithm)
    if safe_framework in {"pytorch", "tensorflow"}:
        safe_algorithm = "mlp"
    elif safe_framework == "xgboost":
        safe_algorithm = "xgboost"
    elif safe_framework == "lightgbm":
        safe_algorithm = "lightgbm"
    if safe_framework in {"pytorch", "tensorflow"}:
        result = _neural_template(requirement, safe_task, safe_framework)
    else:
        result = _sklearn_template(requirement, safe_task, safe_framework, safe_algorithm)
    compile(result, "generated_model.py", "exec")
    return result


def analyse_code(code: str) -> dict[str, Any]:
    tree = ast.parse(code)
    imports = []
    functions = []
    classes = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.extend(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            imports.append(node.module or "")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            functions.append(node.name)
        elif isinstance(node, ast.ClassDef):
            classes.append(node.name)
    return {"imports": sorted(set(imports)), "functions": sorted(set(functions)), "classes": sorted(set(classes))}


